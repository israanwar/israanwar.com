// Generate public/_redirects (Netlify) from the slug rename map, so the 301s
// for old blog URLs can never drift from src/data/slugRenames.js — the same map
// the sitemap, prerender and canonical-post resolver use. Vite copies
// public/_redirects into dist/, where Netlify reads it.
//
// Order matters (Netlify applies the first match):
//   1. apex -> www        (host rule, forced)
//   2. old blog slugs     (301, one hop straight to the canonical slug)
//   3. SPA fallback       (200 rewrite to /index.html for client-side routes
//                          that have no prerendered file: CMS-created posts,
//                          store products, cart/checkout/orders, admin).
//                          Netlify never lets a non-forced rewrite shadow a
//                          real file. Anything else gets dist/404.html with a
//                          real 404 status instead of the homepage (no soft 404).
//
// vercel.json is kept in step for the Vercel preview project that is also
// connected to this repo; production is Netlify.

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const { SLUG_RENAMES } = await import(`file://${projectRoot}/src/data/slugRenames.js`);

const SITE_URL = "https://www.israanwar.com";
// Client-side routes (see src/routes/AppRoutes.jsx) whose pages are not all
// prerendered at build time.
const SPA_ROUTES = [
  "/blog/*",
  "/services/*",
  "/tools/*",
  "/store/*",
  "/cart",
  "/checkout",
  "/orders/*",
  "/order/*",
  "/admin",
  "/admin/*",
];
const pad = (s, n) => s.padEnd(n, " ");

const slugRules = Object.entries(SLUG_RENAMES).map(([oldSlug, newSlug]) => [
  `/blog/${oldSlug}`,
  `/blog/${newSlug}`,
  "301",
]);
const width = Math.max(...slugRules.map(([from]) => from.length)) + 2;

const lines = [
  "# Generated by scripts/generate-redirects.mjs — do not edit by hand.",
  "# Source of truth: src/data/slugRenames.js",
  "",
  "# Apex domain -> www (canonical host)",
  `https://israanwar.com/*  ${SITE_URL}/:splat  301!`,
  `http://israanwar.com/*  ${SITE_URL}/:splat  301!`,
  "",
  "# Old blog slugs -> canonical slugs (single 301 hop)",
  ...slugRules.map(([from, to, status]) => `${pad(from, width)}${to}  ${status}`),
  "",
  "# SPA fallback for client-side routes without a prerendered file",
  ...SPA_ROUTES.map((from) => `${pad(from, 22)}/index.html  200`),
  "",
];

writeFileSync(resolve(projectRoot, "public/_redirects"), lines.join("\n"), "utf8");
console.log(`✓ _redirects regenerated → ${slugRules.length} slug redirects`);
