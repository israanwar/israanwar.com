export function rateName(name, lang) {
  if (lang !== "id") return name;
  return NAMES_ID[name] ?? SERVICE_NAME_ID[name] ?? name;
}

export function rateLabel(label, lang) {
  if (lang !== "id") return label;
  return LABELS_ID[label] ?? label;
}

export function rateItemText(item, lang) {
  return {
    name: rateName(item.name, lang),
    categoryName: rateLabel(item.categoryName, lang),
    section: rateLabel(item.section, lang),
    price: item.custom ? rateLabel(item.price, lang) : item.price,
  };
}
