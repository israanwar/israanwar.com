function localizeText(value, lang) {
  if (value && typeof value === "object" && !Array.isArray(value)) {
    if (lang === "id") return value.id ?? value.ID ?? value.indonesia ?? value.en ?? "";
    return value.en ?? value.EN ?? value.id ?? "";
  }
  if (lang !== "id" || typeof value !== "string") return value;
  return TEXT_ID[value] ?? value;
}

function deepLocalize(value, lang) {
  if (Array.isArray(value)) return value.map((item) => deepLocalize(item, lang));
  if (value && typeof value === "object") {
    const localized = {};
    for (const [key, entry] of Object.entries(value)) {
      if (lang === "id" && key.endsWith("_id")) continue;
      const idKey = `${key}_id`;
      if (lang === "id" && value[idKey]) localized[key] = deepLocalize(value[idKey], lang);
      else localized[key] = deepLocalize(entry, lang);
    }
    return localized;
  }
  return localizeText(value, lang);
}

export function localizePage(page, lang) {
  return deepLocalize(page ?? {}, lang);
}

export function localizeHomepage(homepage, lang) {
  return deepLocalize(homepage ?? {}, lang);
}

export function localizeSiteDescription(description, lang, descriptionId) {
  if (lang === "id" && descriptionId) return localizeText(descriptionId, lang);
  return localizeText(description, lang);
}
