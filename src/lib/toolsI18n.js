export function translateTool(lang, text, params) {
  const raw = lang === "id" ? (TOOLS_ID[text] ?? text) : text;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, key) => params[key] ?? "");
}

// tt("English source", { vars }) — returns the active language's copy.
export function useToolsText() {
  const { lang } = useI18n();
  return useCallback((text, params) => translateTool(lang, text, params), [lang]);
}
